# frozen_string_literal: true

require "rails_helper"

RSpec.describe ::Pangram::TextCleaner do
  describe ".clean" do
    it "strips bbcode quote blocks when ignore_quotes is true" do
      raw = <<~TEXT
        [quote="someone, post:1, topic:2"]
        This was generated by an AI chatbot.
        [/quote]
        This is my actual genuine human reply.
      TEXT

      cleaned = described_class.clean(raw, ignore_quotes: true, ignore_code_blocks: false)
      expect(cleaned).to eq("This is my actual genuine human reply.")
    end

    it "strips markdown blockquotes when ignore_quotes is true" do
      raw = <<~TEXT
        > Quoting someone here
        > Another quote line

        My original thoughts on this topic.
      TEXT

      cleaned = described_class.clean(raw, ignore_quotes: true, ignore_code_blocks: false)
      expect(cleaned).to eq("My original thoughts on this topic.")
    end

    it "strips fenced code blocks and inline code when ignore_code_blocks is true" do
      raw = <<~TEXT
        Here is some code explanation:
        ```ruby
        def hello_world
          puts "hi"
        end
        ```
        And inline `var x = 10;` in text.
      TEXT

      cleaned = described_class.clean(raw, ignore_quotes: false, ignore_code_blocks: true)
      expect(cleaned).to include("Here is some code explanation:")
      expect(cleaned).to include("And inline  in text.")
      expect(cleaned).not_to include("def hello_world")
      expect(cleaned).not_to include("var x = 10;")
    end

    it "retains quotes and code blocks when options are false" do
      raw = "[quote]hello[/quote] ```code``` text"
      cleaned = described_class.clean(raw, ignore_quotes: false, ignore_code_blocks: false)
      expect(cleaned).to eq("[quote]hello[/quote] ```code``` text")
    end
  end

  describe ".word_count" do
    it "counts words accurately on cleaned text" do
      raw = <<~TEXT
        [quote]
        One two three four five six seven eight nine ten
        [/quote]
        Word one, word two, word three.
      TEXT

      count = described_class.word_count(raw, ignore_quotes: true, ignore_code_blocks: true)
      expect(count).to eq(6)
    end
  end
end
